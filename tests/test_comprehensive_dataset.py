@pytest.mark.parametrize(
    "poem_entry",
    CLASSICAL_ARABIC_METERS_DATASET,
    ids=[f"{p['meter']}_{p['variation']}_{p['title'][:15]}" for p in CLASSICAL_ARABIC_METERS_DATASET],
)
def test_classical_dataset_meter_classification(
    processor: ArudhProcessor,
    poem_entry: dict,
) -> None:
    expected_meter = poem_entry["meter"]
    verses = poem_entry["verses"]

    # Test full poem level analysis
    poem_analysis = processor.analyze_poem(verses)
    assert poem_analysis.meter_key == expected_meter, (
        f"Poem '{poem_entry['title']}' expected '{expected_meter}', got '{poem_analysis.meter_key}'"
    )
    assert poem_analysis.average_score >= 0.85

    # Test each verse individually
    for sadr, ajuz in verses:
        analysis = processor.analyze_verse(sadr, ajuz if ajuz else None)
        assert analysis.meter_key == expected_meter, (
            f"Failed on '{sadr}' / '{ajuz}'. Expected meter {expected_meter}, got {analysis.meter_key} "
            f"(Score: {analysis.score})"
        )
        assert analysis.score >= 0.85, f"Confidence score too low ({analysis.score}) for '{sadr}'"
