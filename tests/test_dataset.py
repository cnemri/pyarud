@pytest.fixture
def processor():
    return ArudhProcessor()


@pytest.mark.parametrize("poem_data", ALDIWAN_DATASET, ids=lambda d: f"{d['meter']}_{d['poet']}")
def test_aldiwan_poems_identification(processor, poem_data):
    meter = poem_data["meter"]
    verses = poem_data["verses"]

    # Test full poem level analysis
    poem_analysis = processor.analyze_poem(verses)
    assert poem_analysis.meter_key == meter, (
        f"Poem '{poem_data['title']}' by {poem_data['poet']} expected '{meter}', got '{poem_analysis.meter_key}'"
    )
    assert poem_analysis.average_score >= 0.85

    # Test individual verses
    for sadr, ajuz in verses:
        v_analysis = processor.analyze_verse(sadr, ajuz)
        assert v_analysis.meter_key == meter, (
            f"Verse ({sadr} ... {ajuz}) expected '{meter}', got '{v_analysis.meter_key}'"
        )
        assert v_analysis.score >= 0.85
        assert v_analysis.is_valid is True
