def test_aldiwan_unseen_poem(expected_meter, poem_data):
    """Test that each of the 80 unseen poems from aldiwan.net matches its expected Bahr with high accuracy."""
    verses = poem_data["verses"]
    result = processor.analyze_poem(verses)
    assert result.meter_key == expected_meter, (
        f"Failed on '{poem_data['title']}' by {poem_data['poet']} ({poem_data['url']}): "
        f"expected {expected_meter}, got {result.meter_key} ({result.meter_name_ar}) with score {result.average_score}"
    )
    assert result.average_score >= 0.60, (
        f"Score too low for '{poem_data['title']}': {result.average_score}"
    )
